    private static string GetExtensionClassName(ResultAliasModel model)
    {
        if (string.IsNullOrEmpty(model.ContainingTypeDeclarations))
        {
            return $"{model.AliasName}TaskExtensions";
        }

        var typePath = model.AliasFullyQualifiedName.Replace("global::", string.Empty);
