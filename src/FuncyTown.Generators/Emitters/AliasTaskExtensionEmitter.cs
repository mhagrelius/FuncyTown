    }

    private static string[] SplitParameters(string parameters)
    {
        var parts = new System.Collections.Generic.List<string>();
        var current = new StringBuilder();
        var angleDepth = 0;

        foreach (var ch in parameters)
        {
            switch (ch)
            {
                case '<':
                    angleDepth++;
                    current.Append(ch);
                    break;
                case '>':
                    angleDepth--;
                    current.Append(ch);
                    break;
                case ',' when angleDepth == 0:
                    parts.Add(current.ToString());
                    current.Clear();
                    break;
                default:
                    current.Append(ch);
                    break;
            }
        }

        if (current.Length > 0)
        {
            parts.Add(current.ToString());
        }

        return parts.ToArray();
    }
