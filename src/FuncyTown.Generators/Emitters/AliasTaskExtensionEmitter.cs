            && typePath.StartsWith(model.AliasNamespace + ".", StringComparison.Ordinal))
        {
            typePath = typePath.Substring(model.AliasNamespace.Length + 1);
        }

        return $"{SanitizeIdentifier(typePath)}TaskExtensions";
    }

    private static string GetExtensionClassAccessibility(ResultAliasModel model)
    {
        if (model.AliasAccessibility != "public")
        {
            return "internal";
        }

        if (string.IsNullOrEmpty(model.ContainingTypeDeclarations))
        {
            return "public";
        }

        return model.ContainingTypeDeclarations
            .Split(new[] { '\n' }, StringSplitOptions.RemoveEmptyEntries)
            .All(static declaration => GetModifiers(declaration).Contains("public"))
            ? "public"
            : "internal";
    }

    private static string[] GetModifiers(string declaration)
    {
        var typeKeywordIndex = declaration.IndexOf(" class ", StringComparison.Ordinal);
        if (typeKeywordIndex < 0)
        {
            typeKeywordIndex = declaration.IndexOf(" struct ", StringComparison.Ordinal);
        }

        if (typeKeywordIndex < 0)
        {
            typeKeywordIndex = declaration.IndexOf(" interface ", StringComparison.Ordinal);
        }

        if (typeKeywordIndex < 0)
        {
            typeKeywordIndex = declaration.IndexOf(" record", StringComparison.Ordinal);
        }

        var modifiers = typeKeywordIndex < 0
            ? declaration
            : declaration.Substring(0, typeKeywordIndex);
        return modifiers.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
    }

    private static string SanitizeIdentifier(string value)
    {
        var builder = new StringBuilder(value.Length);
        foreach (var ch in value)
        {
            builder.Append(char.IsLetterOrDigit(ch) || ch == '_' ? ch : '_');
        }

        return builder.ToString();
    }

