    private static bool IsAccessibleContainingType(string declaration, bool isTopLevel)
    {
        if (HasTypeParameters(declaration))
        {
            return false;
        }

        var modifiers = GetModifiers(declaration);
        var hasPrivate = modifiers.Contains("private");
        var hasProtected = modifiers.Contains("protected");
        var hasInternal = modifiers.Contains("internal");
        var hasPublic = modifiers.Contains("public");

        if (hasPrivate || (hasProtected && !hasInternal))
        {
            return false;
        }

        return hasPublic || hasInternal || isTopLevel;
    }

    private static bool IsPublicContainingType(string declaration)
    {
        return !HasTypeParameters(declaration)
            && GetModifiers(declaration).Contains("public");
    }

    private static bool HasTypeParameters(string declaration)
